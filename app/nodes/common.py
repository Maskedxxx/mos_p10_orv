"""
Общие помощники узлов пайплайна П-10 (27.10, модульность: раньше лежали внутри узлов гипотез и Excel,
а брали их и другие узлы).

    run_after                  запуск агента с задержкой — ведомые ждут, пока первый запишет общий текст в кэш
                               (узлы вердиктов и гипотез)
    append_task_clarification  уточнение задачи от пользователя к промпту узла (перезапуск из диалога)
    compute_years              годы бланка запроса показателей (узел запроса и запасной путь узла Excel)

Стоимость вызовов узлы прибавляют к meta.json через app.trace.add_cost.
"""

from __future__ import annotations

import datetime
import time


def run_after(delay_s: float, fn, *args):
    """
    Запустить fn через delay_s секунд (2.6): ведомый агент ждёт, пока первый в группе
    запишет общий текст в кэш — одновременно стартовавшие агенты пишут его каждый сам.
    Общий помощник узлов гипотез и вердиктов.
    """
    if delay_s > 0:
        time.sleep(delay_s)
    return fn(*args)


def append_task_clarification(instruction: str, extra_instruction: str | None) -> str:
    """
    Дописать к промпту узла уточнение задачи от пользователя (диалоговый режим,
    план итерации 3, шаг 1.2). Без уточнения промпт возвращается побайтно прежним.

    Уточнение говорит, ЧТО ещё проверить и ГДЕ искать, но не какой вывод нужен:
    это правило промпта оркестратора, а текст уточнения пользователь видит
    в плане до подтверждения.
    """
    if not extra_instruction:
        return instruction
    return (
        f"{instruction}\n\n<уточнение_задачи>\n"
        "Пользователь уточнил объём проверки. Выполни инструкцию выше полностью "
        "и дополнительно учти уточнение. Оно говорит, что проверить и где искать, "
        "а не к какому выводу прийти.\n\n"
        f"{extra_instruction.strip()}\n</уточнение_задачи>\n"
    )


def compute_years(num_years: int = 4, end_year: int | None = None) -> list[int]:
    """
    Диапазон из num_years лет, заканчивающийся на end_year (перенесено из фазы 2,
    формула диапазона не менялась).

    ПРАВКА владельца 2026-08-24: если end_year не задан явно, по умолчанию
    берётся ПРОШЛЫЙ год (today.year - 1), а не текущий. Текущий год ещё не
    завершился — просить у органа данные за неполный год значит получить
    либо дыру в клетке, либо восемь месяцев вместо двенадцати, оба исхода
    для сравнения не годятся. Явно переданный end_year уважается как есть,
    поправка касается только автоопределения.
    """
    if num_years < 1:
        raise ValueError("num_years должен быть >= 1")
    if end_year is None:
        end_year = datetime.date.today().year - 1
    return list(range(end_year - num_years + 1, end_year + 1))
