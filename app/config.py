SECRETS_FILE = PROJECT_ROOT / ".env.secrets"

ENV_AUTH_USER = "P10_AUTH_USER"
ENV_AUTH_PASSWORD = "P10_AUTH_PASSWORD"
ENV_STORAGE_SECRET = "P10_STORAGE_SECRET"


def load_secrets(path: Path = SECRETS_FILE) -> None:
    """
    Прочитать .env.secrets и разложить его значения по переменным окружения.

    Формат простой: строка «КЛЮЧ=значение». Пустые строки и строки, начинающиеся
    с «#», пропускаются. Делится только первый знак «=», поэтому он может
    встречаться и внутри значения.

    Уже установленная переменная окружения не затирается: заданное снаружи (юнитом
    systemd, окружением теста) сильнее файла. Файла нет — просто выходим, доступы
    могли прийти из окружения; за их наличие отвечает require_auth_settings().
    """
    if not path.is_file():
        return
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        # Комментарий, пустая строка и строка без «=» к доступам отношения не имеют
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        os.environ.setdefault(key.strip(), value.strip())


def auth_user() -> str:
    """Логин для входа на веб-страницу (переменная P10_AUTH_USER)."""
    return os.environ.get(ENV_AUTH_USER, "")


def auth_password() -> str:
    """Пароль для входа на веб-страницу (переменная P10_AUTH_PASSWORD)."""
    return os.environ.get(ENV_AUTH_PASSWORD, "")


def storage_secret() -> str:
    """Ключ подписи пользовательских сессий NiceGUI (P10_STORAGE_SECRET)."""
    return os.environ.get(ENV_STORAGE_SECRET, "")


def require_auth_settings() -> None:
    """
    Убедиться, что доступы заданы, иначе сервису стартовать нельзя.

    Без пароля страница поднялась бы нараспашку в открытый интернет, а один прогон
    стоит около десяти долларов — поэтому это не предупреждение, а отказ запускаться.
    В сообщении только имена незаполненных ключей: значений в нём нет и быть не может.
    """
    missing = [
        name
        for name, value in (
            (ENV_AUTH_USER, auth_user()),
            (ENV_AUTH_PASSWORD, auth_password()),
            (ENV_STORAGE_SECRET, storage_secret()),
        )
        if not value
    ]
    if missing:
        # Склонение по числу пропущенных ключей: сообщение читает человек
        what = "не задан" if len(missing) == 1 else "не заданы"
        raise RuntimeError(
            f"Сервис П-10 не запущен: {what} " + ", ".join(missing) + ". "
            f"Задайте их в файле {SECRETS_FILE} (права 600) или в переменных окружения."
        )
