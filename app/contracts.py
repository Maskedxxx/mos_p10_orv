    rationale_brief: list[BriefPoint] = _brief(_RATIONALE_BRIEF)

    @model_validator(mode="after")
    def _check_name_rationale_missing_data(self) -> "Indicator10Output":
        _not_blank(self.name)
        _not_blank(self.rationale)
        _check_missing_data(self.verdict, self.missing_data)
        return self

    @model_validator(mode="after")
    def _check_verdict_follows_findings(self) -> "Indicator10Output":
        """Вердикт следует из применимости и таблицы фактов (рубрика индикатора 10, раздел 4)."""
        marks = {f.mark for f in self.findings}
        if self.applicability != "применим":
            allowed, why = {"не применимо"}, f"акт: «{self.applicability}»"
        elif "не работает" in marks:
            allowed, why = {"нарушен"}, "есть факт «не работает»"
        elif "работает" in marks:
            allowed, why = {"соблюдён"}, "есть факт «работает», фактов «не работает» нет"
        else:
            allowed, why = {"нет данных"}, "фактов про применение этого акта нет"
        if self.verdict not in allowed:
            raise ValueError(f"вердикт «{self.verdict}» не следует из applicability и findings: {why} — "
                             f"допустимо: {', '.join(sorted(allowed))}")
        return self


