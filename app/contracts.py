Affected = Literal["бизнес", "граждане", "город", "бизнес и граждане"]




# ---- эффект ----------------------------------------------------------


class Effect(_Base):
    """Один измеримый эффект гипотезы для одной группы."""

    affected: Affected = Field(
        description=(
            "Кто несёт этот эффект. «бизнес» — организации и предприниматели, "
            "на которых лежит обязанность или которые обращаются за решением. "
            "«граждане» — физические лица. «город» — бюджет и органы власти "
            "Москвы: их трудозатраты, расходы, недополученные доходы. "
            "«бизнес и граждане» — когда адресаты акта обеих категорий несут "
            "одно и то же. Разные плательщики одного и того же механизма — "
            "это разные эффекты ОДНОЙ гипотезы, а не разные гипотезы."
        )
    )
    metric: str = Field(
        min_length=1,
        description=(
            "Показатель, которым меряется эффект, с единицей измерения: "
            "«издержки одного заявителя на сбор документов, руб.», «доля "
            "несостоявшихся торгов, %», «дополнительный срок ожидания, рабочих "
            "дней». Один показатель — одно измерение. Не «станет хуже», "
            "не «повысится нагрузка»."
        ),
    )
    how_to_calculate: str = Field(
        min_length=1,
        description=(
            "Метод расчёта так, чтобы аналитик повторил его без тебя: какие "
            "величины перемножить или разделить, за какой период, откуда каждая "
            "берётся. Если величина берётся допущением (средняя ставка по "
            "Росстату, типовой норматив времени) — назови допущение явно."
        ),
    )
    expected_trend: str = Field(
        min_length=1,
        description=(
            "Какая динамика показателя подтвердит гипотезу — для аналитика, который "
            "получит цифры от органа. Направление назови явно — рост или снижение; "
            "скажи, относительно чего — год до вступления акта в силу, соседние годы, "
            "аналогичная процедура без этого требования, норматив; и что это покажет. "
            "Пример: «рост доли отказов по п. 2.2 в 2024–2025 относительно 2023 года "
            "покажет, что требование стало барьером; ноль или снижение — гипотеза не "
            "подтверждается». Запрещено: «изменится», «покажет эффект», «будет "
            "наблюдаться динамика» — без направления и точки отсчёта."
        ),
    )


# ---- показатель данных -------------------------------------------------


class DataItem(_Base):
    """Один показатель, нужный для расчёта эффектов гипотезы."""

    metric: str = Field(
        min_length=1,
        description=(
            "Что именно нужно, одним измерением: «количество поданных заявок, "
            "ед., по годам 2023-2025». Без «и/или» внутри — два измерения это "
            "два показателя. Без излишней детализации: разбивку по основаниям "
            "или категориям добавляй только если она нужна для расчёта эффекта."
        ),
    )
    source: SourceKind = Field(
        description=(
            "«запрос органу» — ТОЛЬКО то, что орган-разработчик регистрирует "
            "по своей процедуре: число обращений, отказов и их основания, "
            "выданных решений, повторных подач; сроки по его собственным "
            "журналам; его штат и структура. "
            "«открытый» — всё остальное: статистика Росстата и Мосстата, "
            "тарифы, прайсы, нормативы, тексты актов, сведения с сайтов. "
            "У органа НЕТ и он не даст: времени и издержек заявителя на "
            "подготовку документов, ставок и окладов третьих лиц, числа жалоб "
            "и судебных споров (их ищут в открытых источниках), внутренних "
            "трудозатрат на одну заявку, позиции или мнения по вопросу. "
            "Всё это — «открытый» с указанием, где взять, либо допущение "
            "в методе расчёта."
        )
    )
    where: str | None = Field(
        default=None,
        description=(
            "Где взять — только для «открытый»: конкретный источник, «Росстат, "
            "средняя заработная плата по Москве», «сайт ФНС, тарифы», «прайсы "
            "кадастровых организаций». Для «запрос органу» — null."
        ),
    )

    @model_validator(mode="after")
    def _where_matches_source(self) -> "DataItem":
        """«открытый» обязан сказать где; «запрос органу» — не должен."""
        if self.source == "открытый" and not (self.where and self.where.strip()):
            raise ValueError("source «открытый» требует непустого where")
        if self.source == "запрос органу" and self.where:
            raise ValueError("source «запрос органу» не допускает where")
        return self


# ---- гипотеза ----------------------------------------------------------


class Hypothesis(_Base):
    """
    Одна гипотеза = один механизм последствия нарушения. Разные плательщики
    того же механизма — разные эффекты внутри неё. Другой механизм — другая
    гипотеза.
    """

    hypothesis: str = Field(
        min_length=1,
        description=(
            "К чему приводит нарушение и через какой механизм, одна-две фразы. "
            "Обязательно назови масштаб: сколько лиц или случаев затронуто, "
            "добровольна ли процедура, велик ли пакет. Если ставка заведомо "
            "мала — так и напиши, гипотезу не выбрасывай. "
            "Для рода «дефект нормы» — назови сам дефект (устаревшая ссылка, "
            "дубль нормы, бессрочность, неясная формулировка) и что он значит "
            "для адресата; НЕ выводи из него накопление издержек. "
            "Для вердикта «нет данных» — не подозрение, а вопрос с якорем: "
            "«норма п. N возлагает Y; неизвестно, исполняется ли и во что "
            "обходится; если Z — издержки для W». Гипотеза об акте, не о поиске. "
            "Не пересказывай вердикт и не цитируй акт — для цитаты есть proof. "
            "Об отсутствии чего-либо говори «в тексте акта не установлено», "
            "а не «отсутствует» — за пределами акта ты не проверял."
        ),
    )
    grounds: str = Field(
        min_length=1,
        description=(
            "На чём стоит гипотеза — ДОСЛОВНО из карточки вердикта: для "
            "«нарушен» — формулировка нарушения из rationale; для «нет данных» — "
            "фраза из rationale или missing_data, из которой вырос вопрос. "
            "Своими словами пересказывать нельзя, вводить утверждение, которого "
            "в карточке нет, — нельзя. Если для гипотезы нет опоры в карточке, "
            "гипотезы нет."
        ),
    )
    effects: list[Effect] = Field(
        min_length=1,
        description=(
            "Все измеримые эффекты этого механизма, по одному на группу-"
            "плательщика. Один эффект — норма. Два — когда механизм один, "
            "а платят разные (заявитель и орган). Не заводи второй эффект "
            "только ради второй метрики для той же группы — выбери одну, "
            "лучше измеримую."
        ),
    )
    data: list[DataItem] = Field(
        min_length=1,
        description=(
            "Показатели для расчёта ВСЕХ эффектов гипотезы. Каждый показатель "
            "должен использоваться хотя бы в одном how_to_calculate; показатель, "
            "который ни в одном расчёте не участвует, сюда не входит. "
            "Показатель, который выводится из уже названных (среднее из "
            "минимума и максимума, доля из двух количеств), не запрашивается. "
            "Если акт — проект или норма ещё не вступила в силу, статистику "
            "применения не запрашивай: её не существует."
        ),
    )
    proof: str | None = Field(
        default=None,
        description=(
            "Дословная цитата пункта акта из карточки вердикта, не своя. "
            "Для «нет данных» — цитата пункта, на который опирается вопрос; "
            "null только если вопрос к процедуре в целом, без опорного пункта."
        ),
    )
    clause: str | None = Field(
        default=None,
        description="Номер пункта из карточки вердикта, не свой.",
    )

    @model_validator(mode="after")
    def _effects_distinct_groups(self) -> "Hypothesis":
        """Два эффекта одной группе — это дробление метрик, а не разные плательщики."""
        groups = [e.affected for e in self.effects]
        if len(groups) != len(set(groups)):
            raise ValueError("в одной гипотезе не может быть двух эффектов для одной группы")
        return self


# ---- набор по индикатору -------------------------------------------------


class HypothesisSet(_Base):
    """Гипотезы по одному индикатору из одной карточки вердикта."""

    indicator: int = Field(ge=1, le=12, description="Номер индикатора из карточки вердикта.")
    name: str = Field(min_length=1, description="Название индикатора из карточки вердикта.")
    violation_kind: ViolationKind | None = Field(
        default=None,
        description=(
            "Род нарушения; обязателен, когда в hypotheses есть хотя бы одна "
            "гипотеза (null допустим только у пустого набора при сбое узла). "
            "Вопрос-разрешитель: если норму исправить, что "
            "изменится у адресата завтра? Деньги или время — «издержки»: "
            "гипотеза о последствии, эффект — величина потерь. Ничего "
            "немедленно, но снят правовой риск — «дефект нормы»: гипотеза "
            "называет дефект, эффект — масштаб охвата (сколько лиц и каких "
            "расходов под требованием). Ориентир, не жёсткое правило: "
            "индикаторы 3, 4, 6, 9 чаще «дефект нормы», остальные — «издержки». "
            "Решай по нарушению из карточки, а не по номеру индикатора."
        )
    )
    why_this_many: str = Field(
        min_length=1,
        description=(
            "Почему гипотез именно столько. Назови механизмы последствий, "
            "которые ты увидел, и почему каждый — отдельная гипотеза, а не "
            "эффект внутри соседней. «Разные метрики и разные источники "
            "данных» — НЕ основание для отдельной гипотезы: это основание "
            "для второго эффекта."
        ),
    )
    hypotheses: list[Hypothesis] = Field(
        default_factory=list,
        description=(
            "Гипотезы. Пусто допустимо только если ни для одного механизма "
            "нельзя назвать и показатель, и источник данных — объясни это "
            "в why_this_many."
        ),
    )

    @model_validator(mode="after")
    def _kind_required_with_hypotheses(self) -> "HypothesisSet":
        """Род нарушения нельзя не назвать, если гипотезы написаны."""
        if self.hypotheses and self.violation_kind is None:
            raise ValueError("violation_kind обязателен, когда есть хотя бы одна гипотеза")
        return self


