class Hypothesis(_Base):
    """
    Одна гипотеза = один механизм последствия нарушения. Разные плательщики
    того же механизма — разные эффекты внутри неё. Другой механизм — другая
    гипотеза.
    """

    hypothesis: str = Field(
        min_length=1,
        description=(
            "К чему приводит нарушение и через какой механизм, одна-две фразы. "
            "Обязательно назови масштаб: сколько лиц или случаев затронуто, "
            "добровольна ли процедура, велик ли пакет. Если ставка заведомо "
            "мала — так и напиши, гипотезу не выбрасывай. "
            "Для рода «дефект нормы» — назови сам дефект (устаревшая ссылка, "
            "дубль нормы, бессрочность, неясная формулировка) и что он значит "
            "для адресата; НЕ выводи из него накопление издержек. "
            "Для вердикта «нет данных» — не подозрение, а вопрос с якорем: "
            "«норма п. N возлагает Y; неизвестно, исполняется ли и во что "
            "обходится; если Z — издержки для W». Гипотеза об акте, не о поиске. "
            "Не пересказывай вердикт и не цитируй акт — для цитаты есть proof. "
            "Об отсутствии чего-либо говори «в тексте акта не установлено», "
            "а не «отсутствует» — за пределами акта ты не проверял."
        ),
    )
    grounds: str = Field(
        min_length=1,
        description=(
            "На чём стоит гипотеза — ДОСЛОВНО из карточки вердикта: для "
            "«нарушен» — формулировка нарушения из rationale; для «нет данных» — "
            "фраза из rationale или missing_data, из которой вырос вопрос. "
            "Своими словами пересказывать нельзя, вводить утверждение, которого "
            "в карточке нет, — нельзя. Если для гипотезы нет опоры в карточке, "
            "гипотезы нет."
        ),
    )
    effects: list[Effect] = Field(
        min_length=1,
        description=(
            "Все измеримые эффекты этого механизма, по одному на группу-"
            "плательщика. Один эффект — норма. Два — когда механизм один, "
            "а платят разные (заявитель и орган). Не заводи второй эффект "
            "только ради второй метрики для той же группы — выбери одну, "
            "лучше измеримую."
        ),
    )
    data: list[DataItem] = Field(
        min_length=1,
        description=(
            "Показатели для расчёта ВСЕХ эффектов гипотезы. Каждый показатель "
            "должен использоваться хотя бы в одном how_to_calculate; показатель, "
            "который ни в одном расчёте не участвует, сюда не входит. "
            "Показатель, который выводится из уже названных (среднее из "
            "минимума и максимума, доля из двух количеств), не запрашивается. "
            "Если акт — проект или норма ещё не вступила в силу, статистику "
            "применения не запрашивай: её не существует."
        ),
    )
    proof: str | None = Field(
        default=None,
        description=(
            "Дословная цитата пункта акта из карточки вердикта, не своя. "
            "Для «нет данных» — цитата пункта, на который опирается вопрос; "
            "null только если вопрос к процедуре в целом, без опорного пункта."
        ),
    )
    clause: str | None = Field(
        default=None,
        description="Номер пункта из карточки вердикта, не свой.",
    )
    hypothesis_brief: list[str] | None = Field(default=None, description=_HYPOTHESIS_BRIEF)
    grounds_brief: list[str] | None = Field(default=None, description=_GROUNDS_BRIEF)

    @model_validator(mode="after")
    def _effects_distinct_groups(self) -> "Hypothesis":
        """Два эффекта одной группе — это дробление метрик, а не разные плательщики."""
        groups = [e.affected for e in self.effects]
        if len(groups) != len(set(groups)):
            raise ValueError("в одной гипотезе не может быть двух эффектов для одной группы")
        return self


