"""
Контракты данных сервиса П-10.

Все модели — pydantic v2, extra="forbid" (лишние поля отвергаются).
КРИТИЧНО: имена полей только латиницей — `claude -p --json-schema` отвергает
кириллические ключи (regex '^[a-zA-Z0-9_.-]{1,64}$'). Значения полей (enum'ы,
строки) могут быть кириллицей.

ОПИСАНИЯ ПОЛЕЙ (Field(description=...)) — ЧАСТЬ ПРОМПТА: pydantic кладёт их
в JSON-схему, схема уходит модели вместе с заданием как мини-инструкция к каждому
полю. У контрактов structured output (паспорт, гипотезы, карта, запрос) описание
обязано быть у КАЖДОГО поля — это проверяет tests/test_contracts.py.

Состав (v2, сентябрь 2026, по ОС экспертов и карте паспорта):
- Verdict, Buckets — вердикты индикаторов и их кучи (узлы [2], [3]);
- Effect, DataItem, Hypothesis, HypothesisSet — гипотезы (узлы [4а]/[4б]):
  несколько эффектов на гипотезу, основание из карточки вердикта, род нарушения;
- MapRow, Merge, PairDecision, HypothesisMap — карта (узел [5]): решения по
  кандидатам на слияние; MergeOutput — строгая форма карты для ответа модели;
- SourceRef, RequestItem, DataRequest — запрос показателей (узел [6]): единица
  измерения перечислением, род позиции, происхождение, пояснение; RequestOutput —
  строгая форма бланка для ответа модели;
- ActPassport и вложенные — паспорт акта (узел [1.1], вместо саммари);
- RunMeta, NodeState, RunProgress, RunResult — служебные.
"""

from __future__ import annotations

import re
from typing import Literal, Union

from pydantic import BaseModel, ConfigDict, Field, model_validator

# Допустимые значения вердикта по индикатору
VerdictValue = Literal["нарушен", "соблюдён", "не применимо", "нет данных", "ошибка"]

# Источник показателя данных: открытый (интернет) или запрос органу-разработчику
SourceKind = Literal["открытый", "запрос органу"]


def _not_blank(value: str) -> str:
    """Проверка: строка не пустая и не состоит из одних пробелов после strip."""
    if not value.strip():
        raise ValueError("строка не может быть пустой")
    return value


class _Base(BaseModel):
    """
    Общий предок контрактов structured output: лишние поля отвергаются, а любое
    ОБЯЗАТЕЛЬНОЕ строковое поле не может быть пустым или из одних пробелов
    (min_length=1 пропускает «   », поэтому проверка отдельная).
    """

    model_config = ConfigDict(extra="forbid")

    @model_validator(mode="after")
    def _required_strings_not_blank(self):
        for name, info in type(self).model_fields.items():
            if info.annotation is str and info.is_required():
                value = getattr(self, name)
                if isinstance(value, str) and not value.strip():
                    raise ValueError(f"поле {name} не может быть пустым")
        return self


class Verdict(BaseModel):
    """Вердикт по одному индикатору из 12 (узел [2] пайплайна)."""

    model_config = ConfigDict(extra="forbid")

    indicator: int = Field(ge=1, le=12)
    name: str
    verdict: VerdictValue
    rationale: str
    missing_data: str | None = None
    proof: str | None = None
    clause: str | None = None
    sources: list[str] = Field(default_factory=list)
    attempts: int = Field(default=1, ge=1)

    @model_validator(mode="after")
    def _check_name_rationale(self) -> "Verdict":
        _not_blank(self.name)
        _not_blank(self.rationale)
        return self

    @model_validator(mode="after")
    def _check_missing_data_consistency(self) -> "Verdict":
        """missing_data осмысленно ТОЛЬКО при verdict == "нет данных" и обязано
        быть заполнено в этом случае; при других вердиктах должно быть None
        (включая verdict == "ошибка" — причина ошибки пишется в rationale)."""
        if self.verdict == "нет данных":
            if self.missing_data is None or not self.missing_data.strip():
                raise ValueError(
                    'при verdict == "нет данных" поле missing_data обязано быть заполнено'
                )
        else:
            if self.missing_data is not None:
                raise ValueError(
                    'поле missing_data допустимо только при verdict == "нет данных"'
                )
        return self


class Buckets(BaseModel):
    """Разбор корзины вердиктов на 4 кучи (узел [3] пайплайна)."""

    model_config = ConfigDict(extra="forbid")

    violated: list[Verdict] = Field(default_factory=list)
    no_data: list[Verdict] = Field(default_factory=list)
    checked: list[Verdict] = Field(default_factory=list)
    failed: list[Verdict] = Field(default_factory=list)



