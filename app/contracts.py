class HypothesisMap(_Base):
    """Итоговая карта гипотез: строки, выполненные слияния, решения по кандидатам."""

    rows: list[MapRow] = Field(
        default_factory=list,
        description=(
            "Строки карты по порядку row_id. Каждая исходная гипотеза либо стала "
            "своей строкой дословно, либо вошла в слитую строку — третьего нет."
        ),
    )
    merges: list[Merge] = Field(
        default_factory=list,
        description=(
            "Все выполненные слияния. Пусто — если слияний не было; тогда строк "
            "столько же, сколько гипотез на входе."
        ),
    )
    decisions: list[PairDecision] = Field(
        default_factory=list,
        description=(
            "Решение по КАЖДОЙ паре из блока «КАНДИДАТЫ НА СЛИЯНИЕ» входа — "
            "ровно столько записей, сколько кандидатов, ни одной не пропустив. "
            "Слияния сверх кандидатов допустимы (объясни в merges.reason), "
            "кандидат без решения — нет."
        ),
    )

    @model_validator(mode="after")
    def _check_consistency(self) -> "HypothesisMap":
        """row_id уникальны и по возрастанию; слияния не пересекаются; решения «слить» ↔ слияния."""
        ids = [r.row_id for r in self.rows]
        if ids != sorted(set(ids)):
            raise ValueError("row_id должны быть уникальны и идти по возрастанию")
        seen: set[int] = set()
        for m in self.merges:
            overlap = seen & set(m.merged_row_ids)
            if overlap:
                raise ValueError(f"исходные строки {sorted(overlap)} входят в два слияния")
            seen |= set(m.merged_row_ids)
        merged_sets = [set(m.merged_row_ids) for m in self.merges]
        for d in self.decisions:
            pair = set(d.row_ids)
            in_merge = any(pair <= s for s in merged_sets)
            if d.merge and not in_merge:
                raise ValueError(f"решение «слить» по паре {sorted(pair)} без соответствующего слияния")
            if not d.merge and in_merge:
                raise ValueError(f"пара {sorted(pair)} слита, но решение по ней — «не сливать»")
        return self


class MergeOutput(HypothesisMap):
    """Итоговая карта гипотез: строки, выполненные слияния, решения по кандидатам."""

    # Строгая форма карты для ОТВЕТА МОДЕЛИ узла [5]: свежая карта нумеруется с 1 подряд.
    # Хранимая карта (HypothesisMap) допускает дырки — после удаления строки в диалоговом
    # режиме номер закреплён за строкой (план итерации 3, шаг 1.3). Проверка живёт здесь,
    # а не в коде узла: runner.call ловит её и просит модель исправиться через --resume.
    # Заголовок и описание те же, что у базы; с 2.5 строки ответа — MapRowOutput: выжимки
    # для эксперта в ответе модели обязательны (в хранимой карте — нет).
    model_config = ConfigDict(title="HypothesisMap")

    # 2.5: строки ответа — со строгими выжимками для эксперта
    rows: list[MapRowOutput] = Field(default_factory=list, description=HypothesisMap.model_fields["rows"].description)

    @model_validator(mode="after")
    def _check_fresh_numbering(self) -> "MergeOutput":
        ids = [r.row_id for r in self.rows]
        if ids != list(range(1, len(ids) + 1)):
            raise ValueError("row_id должны идти сквозной нумерацией с 1")
        return self


