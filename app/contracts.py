    @model_validator(mode="after")
    def _check_to_request_only_with_no_data(self) -> "Indicator10Output":
        """14.10: числа для органа — при «нет данных» обязательны, при других вердиктах их нет."""
        if self.verdict == "нет данных" and not self.to_request:
            raise ValueError("при «нет данных» to_request обязателен: перечисли числа, которые запросить у органа")
        if self.verdict != "нет данных" and self.to_request:
            raise ValueError("to_request заполняется только при «нет данных»")
        return self

    @model_validator(mode="after")
    def _check_verdict_follows_findings(self) -> "Indicator10Output":
        ids = [t.target_id for t in self.targets]
        if len(ids) != len(set(ids)):
            raise ValueError("targets: повтор target_id")
        coverage_ids = [c.target_id for c in self.coverage]
        if sorted(coverage_ids) != sorted(ids):
            raise ValueError("coverage должна содержать каждую цель ровно один раз")
        if self.applicability != "применим":
            if self.targets or self.coverage or self.findings:
                raise ValueError("при неприменимости targets, coverage и findings пусты")
            expected = "не применимо"
        else:
            if not ids:
                raise ValueError("применимый акт требует targets")
            if any(f.target_id not in ids for f in self.findings):
                raise ValueError("findings ссылается на неизвестную цель")
            for c in self.coverage:
                if any(i < 1 or i > len(self.findings) for i in c.finding_indices):
                    raise ValueError("coverage: неизвестный номер находки")
                facts = [self.findings[i-1] for i in c.finding_indices]
                if any(f.target_id != c.target_id for f in facts):
                    raise ValueError("находка относится к другой цели")
                if c.status == "подтверждено" and not any(f.mark in ("работает", "не работает") for f in facts):
                    raise ValueError("подтверждённая цель требует подтверждающей находки")
                if c.status == "не установлено" and not (c.gap and c.gap.strip()):
                    raise ValueError("незакрытая цель требует gap")
            uncovered = {c.target_id for c in self.coverage if c.status == "не установлено"}
            if any(r.target_id not in uncovered for r in self.to_request):
                raise ValueError("to_request должен относиться к незакрытой цели")
            if any(f.mark == "не работает" for f in self.findings):
                expected = "нарушен"
            elif uncovered:
                expected = "нет данных"
            else:
                expected = "соблюдён"
        if self.verdict != expected:
            raise ValueError(f"вердикт не следует из applicability, findings и coverage: ожидается «{expected}»")
        return self


