# ---- корень -----------------------------------------------------------


class ActPassport(_Base):
    """Паспорт нормативного правового акта: структурное описание объектов,
    адресатов, существенных условий и пунктов, в которых они установлены.
    Не оценивай нарушения и не давай рекомендаций. Сохраняй содержание условий
    и исключений; ссылка на пункт не заменяет их. Различай самостоятельные
    объекты и связанные подпункты одного объекта. Для одинакового объекта
    в нескольких местах сохраняй все адреса с указанием приложений."""

    requisites: Requisites = Field(description="Реквизиты акта.")
    status: StatusInfo = Field(description="Статус: проект или принят, с какой даты действует.")
    addressee: AddresseeInfo = Field(description="Кому обращён акт.")
    nature: NatureInfo = Field(description="Что акт делает как документ и на чём основан.")
    requirements: Requirements = Field(description="Поле A. Обязательные требования.")
    procedure: Procedure = Field(description="Поле B. Процедура с участием внешнего лица.")
    documents: Documents = Field(description="Поле C. Документы, которые подаёт лицо.")
    deadlines: Deadlines = Field(description="Поле D. Сроки.")
    references: References = Field(description="Поле F. Ссылки на акты и органы.")
    allocation: Allocation = Field(description="Поле G. Распределение и допуск.")
    control: Control = Field(description="Поле H. Контрольные и надзорные действия.")

    @model_validator(mode="after")
    def _check_state_matches_content(self) -> "ActPassport":
        """Состояние «есть» обязано подкрепляться содержимым, «нет» — не противоречить ему."""
        pairs = [
            ("requirements", self.requirements, self.requirements.groups),
            ("documents", self.documents, self.documents.items),
            ("deadlines", self.deadlines, self.deadlines.items),
            ("references", self.references, self.references.acts + self.references.authorities),
            ("allocation.appointed", self.allocation.appointed, self.allocation.appointed.items),
        ]
        for name, block, items in pairs:
            if block.state == "есть" and not items:
                raise ValueError(f"поле {name}: состояние «есть», но перечень пуст")
            if block.state == "нет" and items:
                raise ValueError(f"поле {name}: состояние «нет», но перечень не пуст")
        if self.procedure.state == "есть" and not self.procedure.clauses:
            raise ValueError("поле procedure: состояние «есть», но пункты не названы")
        if self.control.state == "есть" and not self.control.clauses:
            raise ValueError("поле control: состояние «есть», но пункты не названы")
        return self

    @model_validator(mode="after")
    def _check_project_has_no_requisites(self) -> "ActPassport":
        """Проект узнаётся по отсутствию номера и даты принятия."""
        if self.status.status == "проект" and self.requisites.number and self.requisites.date:
            raise ValueError(
                "статус «проект», но у акта есть и номер, и дата принятия — "
                "проверь признак заново"
            )
        return self

    @model_validator(mode="after")
    def _check_input_kind_matches_actions(self) -> "ActPassport":
        """«акт изменений не вносит» несовместимо с действием «вносит изменения»."""
        has_amend = any(a.action == "вносит изменения" for a in self.nature.actions)
        if has_amend and self.nature.input_kind == "акт изменений не вносит":
            raise ValueError(
                "среди действий есть «вносит изменения», но input_kind говорит обратное"
            )
        if not has_amend and self.nature.input_kind in (
            "только изменяющий акт", "и то и другое", "утверждает своё и изменяет другие акты",
        ):
            raise ValueError(
                "input_kind предполагает предписания об изменениях, но в actions нет «вносит изменения»"
            )
        return self


