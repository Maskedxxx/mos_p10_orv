    @model_validator(mode="after")
    def _effects_distinct_groups(self) -> "Hypothesis":
        """Два эффекта одной группе — это дробление метрик, а не разные плательщики."""
        groups = [e.affected for e in self.effects]
        if len(groups) != len(set(groups)):
            raise ValueError("в одной гипотезе не может быть двух эффектов для одной группы")
        return self


