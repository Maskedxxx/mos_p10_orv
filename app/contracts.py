def _not_blank(value: str) -> str:
    """Проверка: строка не пустая и не состоит из одних пробелов после strip."""
    if not value.strip():
        raise ValueError("строка не может быть пустой")
    return value


class _Base(BaseModel):
    """
    Общий предок контрактов structured output: лишние поля отвергаются, а любое
    ОБЯЗАТЕЛЬНОЕ строковое поле не может быть пустым или из одних пробелов
    (min_length=1 пропускает «   », поэтому проверка отдельная).
    """

    model_config = ConfigDict(extra="forbid")

    @model_validator(mode="after")
    def _required_strings_not_blank(self):
        for name, info in type(self).model_fields.items():
            if info.annotation is str and info.is_required():
                value = getattr(self, name)
                if isinstance(value, str) and not value.strip():
                    raise ValueError(f"поле {name} не может быть пустым")
        return self


