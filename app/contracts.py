class HypothesisMap(_Base):
    """Карта исходных гипотез и вопросов к практике: сохранённые строки, обоснованные полные слияния и решения о пересечениях."""

    rows: list[MapRow] = Field(
        default_factory=list,
        description=(
            "Строки карты по порядку row_id. Каждая исходная гипотеза либо стала "
            "своей строкой дословно, либо вошла в слитую строку — третьего нет."
        ),
    )
    merges: list[Merge] = Field(
        default_factory=list,
        description=(
            "Все выполненные слияния. Пусто — если слияний не было; тогда строк "
            "столько же, сколько гипотез на входе."
        ),
    )
    decisions: list[PairDecision] = Field(
        default_factory=list,
        description=(
            "Решения по каждой входной паре-кандидату и дополнительным обнаруженным парам вне списка. Номера относятся к исходным гипотезам. Пропуск кандидата отражается диагностикой; решение без оснований не подменяет смысловую проверку."
        ),
    )

    @model_validator(mode="after")
    def _check_consistency(self) -> "HypothesisMap":
        """row_id уникальны и по возрастанию; слияния не пересекаются; решения «слить» ↔ слияния."""
        ids = [r.row_id for r in self.rows]
        if ids != sorted(set(ids)):
            raise ValueError("row_id должны быть уникальны и идти по возрастанию")
        seen: set[int] = set()
        for m in self.merges:
            overlap = seen & set(m.merged_row_ids)
            if overlap:
                raise ValueError(f"исходные строки {sorted(overlap)} входят в два слияния")
            seen |= set(m.merged_row_ids)
        merged_sets = [set(m.merged_row_ids) for m in self.merges]
        for d in self.decisions:
            pair = set(d.row_ids)
            in_merge = any(pair <= s for s in merged_sets)
            if d.merge and not in_merge:
                raise ValueError(f"решение «слить» по паре {sorted(pair)} без соответствующего слияния")
            if not d.merge and in_merge:
                raise ValueError(f"пара {sorted(pair)} слита, но решение по ней — «не сливать»")
        return self


class MergeOutput(HypothesisMap):
    """Карта исходных гипотез и вопросов к практике: сохранённые строки, обоснованные полные слияния и решения о пересечениях."""

    # Строгая форма карты для ОТВЕТА МОДЕЛИ узла [5]: свежая карта нумеруется с 1 подряд.
    # Хранимая карта (HypothesisMap) допускает дырки — после удаления строки в диалоговом
    # режиме номер закреплён за строкой (план итерации 3, шаг 1.3). Проверка живёт здесь,
    # а не в коде узла: runner.call ловит её и просит модель исправиться через --resume.
    # Заголовок и описание те же, что у базы; с 2.5 строки ответа — MapRowOutput: выжимки
    # для эксперта в ответе модели обязательны (в хранимой карте — нет).
    model_config = ConfigDict(title="HypothesisMap")

    # 2.5: строки ответа — со строгими выжимками для эксперта
    rows: list[MapRowOutput] = Field(default_factory=list, description=HypothesisMap.model_fields["rows"].description)

    @model_validator(mode="after")
    def _check_fresh_numbering(self) -> "MergeOutput":
        import json
        for row in self.rows:
            for field in ("effects", "data"):
                entries = [json.dumps(item.model_dump(mode="json"), ensure_ascii=False, sort_keys=True)
                           for item in getattr(row, field)]
                if len(entries) != len(set(entries)):
                    raise ValueError(f"строка {row.row_id}: точная копия записи в {field}; сохрани её один раз")
        ids = [r.row_id for r in self.rows]
        if ids != list(range(1, len(ids) + 1)):
            raise ValueError("row_id должны идти сквозной нумерацией с 1")
        return self

    @model_validator(mode="after")
    def _check_merge_input_preserved(self, info: ValidationInfo) -> "MergeOutput":
        for decision in self.decisions:
            if len(set(decision.row_ids)) != 2:
                raise ValueError("decisions: требуются два разных исходных ID")
            if decision.overlap is not None:
                if not decision.overlap.strip() or decision.merge or not (decision.accounting_note and decision.accounting_note.strip()):
                    raise ValueError("частичное пересечение требует merge=false, overlap и accounting_note")
            elif decision.accounting_note is not None:
                raise ValueError("accounting_note требует установленной общей части overlap")
        context = info.context or {}
        if "merge_inputs" not in context:
            return self
        inputs = {item["row_id"]: item for item in context["merge_inputs"]}
        known = set(inputs)
        groups = []
        used = set()
        for merge in self.merges:
            ids = merge.merged_row_ids
            if len(ids) != len(set(ids)) or not set(ids) <= known:
                raise ValueError("merges: повтор или неизвестный исходный ID")
            groups.append(sorted(ids))
            used.update(ids)
        groups.extend([i] for i in sorted(known - used))
        groups.sort(key=min)
        if len(self.rows) != len(groups):
            raise ValueError("потеря исходных строк: rows не соответствуют отдельным гипотезам и объявленным merges")
        seen_pairs = set()
        for decision in self.decisions:
            pair = frozenset(decision.row_ids)
            if not pair <= known or pair in seen_pairs:
                raise ValueError("decisions: неизвестная или повторная пара исходных ID")
            seen_pairs.add(pair)

        def preserved(expected, actual):
            # Old inputs may lack briefs. A new brief derived from the full field is allowed;
            # existing source text, values and nonempty briefs must stay unchanged.
            if isinstance(expected, dict):
                return isinstance(actual, dict) and all(
                    (key.endswith("_brief") and value is None) or
                    (key in actual and preserved(value, actual[key])) for key, value in expected.items())
            if isinstance(expected, list):
                return isinstance(actual, list) and len(expected) == len(actual) and all(
                    preserved(a, b) for a, b in zip(expected, actual))
            return expected == actual

        def joined(items, key, separator):
            values = list(dict.fromkeys(item[key] for item in items if item.get(key)))
            return separator.join(values) if values else None

        def data_with_origins(items):
            import json
            result = {}
            for item in items:
                payload = {key: value for key, value in item.items() if key != "origin_request_ids"}
                signature = json.dumps(payload, ensure_ascii=False, sort_keys=True)
                result.setdefault(signature, set()).update(item.get("origin_request_ids", []))
            return result

        for row, ids in zip(self.rows, groups):
            original = [inputs[i] for i in ids]
            if row.indicators != sorted({item["indicator"] for item in original}):
                raise ValueError(f"строка {row.row_id}: потеря/подмена исходных indicators")
            output = row.model_dump(mode="json", exclude={"row_id", "indicators"})
            if len(ids) == 1:
                expected = {key: value for key, value in original[0].items() if key not in ("row_id", "indicator")}
                if not preserved(expected, output):
                    raise ValueError(f"строка {row.row_id}: неслитая гипотеза должна сохранять все исходные поля дословно")
                continue
            for field, separator in (("grounds", " | "), ("proof", "; "), ("clause", "; ")):
                if output[field] != joined(original, field, separator):
                    raise ValueError(f"строка {row.row_id}: {field} не сохраняет все исходные значения в порядке ID")
            effects = [effect for item in original for effect in item["effects"]]
            if (any(not any(preserved(effect, candidate) for candidate in output["effects"]) for effect in effects)
                    or any(not any(preserved(effect, candidate) for effect in effects) for candidate in output["effects"])):
                raise ValueError(f"строка {row.row_id}: исходные эффекты/методы/единицы должны сохраниться без переписывания")
            if data_with_origins([data for item in original for data in item["data"]]) != data_with_origins(output["data"]):
                raise ValueError(f"строка {row.row_id}: потеря/подмена исходных данных или origin_request_ids")
        return self



