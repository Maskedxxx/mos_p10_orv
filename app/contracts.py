        if _TWO_MEASURES_RE.search(self.metric):
            raise ValueError(f"позиция {self.num}: две величины в одной формулировке — раздели на две позиции")
        if self.kind == "показатель по годам" and self.unit is None:
            raise ValueError(f"позиция {self.num}: у показателя по годам обязана быть единица измерения")
        if self.kind == "перечень или реестр" and self.unit is not None:
            raise ValueError(f"позиция {self.num}: у перечня единицы измерения нет")
        if self.kind == "открытый вопрос":
            if self.unit is not None or self.breakdown:
                raise ValueError(f"позиция {self.num}: у открытого вопроса нет единицы и разрезов")
            if not (self.clause and self.clause.strip()):
                raise ValueError(f"позиция {self.num}: у открытого вопроса обязателен пункт акта")
        # 2.7 (АМ): позиция держится на строках карты, на обязательном показателе или на обоих
        if not self.sources and not self.mandatory:
            raise ValueError(f"позиция {self.num}: ни строки карты, ни обязательного показателя")
        if self.kind == "открытый вопрос" and not self.for_rows:
            raise ValueError(f"позиция {self.num}: открытый вопрос вытекает из строки карты — нужен её номер")
        if self.for_rows != sorted(set(self.for_rows)):
            raise ValueError(f"позиция {self.num}: for_rows по возрастанию, без повторов")
        if set(self.for_rows) != {s.row_id for s in self.sources}:
            raise ValueError(f"позиция {self.num}: for_rows должны совпадать со строками из sources")
        if any(re.match(r"^\s*по\s+(основани|причин)\w*\s*(,|\(|пункт|п\.)?", b, re.IGNORECASE)
               and not re.search(r":|—|–", b) for b in self.breakdown):
            raise ValueError(f"позиция {self.num}: разрез «по основаниям» без перечисления — назови каждое основание")
        return self


