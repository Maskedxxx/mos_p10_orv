        missing, unknown = expected - present, present - expected
        if missing or unknown:
            raise ValueError("Связи исходных показателей: пропущены ID " + str(sorted(missing)) +
                             "; неизвестные ID " + str(sorted(unknown)) +
                             ". Сохрани исходные числа в данных соответствующих гипотез и скопируй request_id. "
                             "Не добавляй все показатели в первую гипотезу; расположение определяется механизмом.")
        return self



